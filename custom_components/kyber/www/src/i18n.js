// ?? Locale registry ??????????????????????????????????????????????????????????
const LOCALES = { en: EN, nl: NL, de: DE, fr: FR, es: ES, it: IT, pt: PT, pl: PL, hu: HU, sv: SV, ru: RU, zh: ZH };

/**
 * Returns a translation function for the given language tag.
 * Falls back gracefully: "nl-BE" → nl → en.
 *
 * Placeholders: t("plan_failed", { n: 2, msg: "x" }) fills "{n}" and "{msg}".
 * Unknown placeholders stay as they are.
 *
 * Plurals: "{n|# fact|# facts}" picks the first form when params.n is 1 and
 * the second otherwise; "#" becomes the value. Works for any placeholder and
 * any number of them per text: "{facts|# fact|# facts} · {errors|# error|# errors}".
 *
 * @param {string} lang  e.g. "nl", "nl-BE", "en", "de"
 * @returns {function(string, Object=): string}
 */
export function getT(lang = "en") {
  const base = (lang || "en").split("-")[0].toLowerCase();
  const locale = LOCALES[lang] || LOCALES[base] || {};
  return (key, params) => {
    const text = locale[key] ?? EN[key] ?? key;
    if (!params) return text;
    return text
      .replace(/\{(\w+)\|([^|{}]*)\|([^{}]*)\}/g, (m, name, one, other) => {
        if (!(name in params)) return m;
        const value = String(params[name]);
        return (Number(params[name]) === 1 ? one : other).replace(/#/g, value);
      })
      .replace(/\{(\w+)\}/g, (m, name) => (name in params ? String(params[name]) : m));
  };
}
